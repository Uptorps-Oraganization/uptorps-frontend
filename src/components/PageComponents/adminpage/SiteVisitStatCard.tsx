const chartConfig = {
  views: {
    label: "Site Views",
  },
  desktop: {
    label: "Desktop",
    color: "var(--color-green-400)",
  },
  mobile: {
    label: "Mobile",
    color: "var(--color-green-300)",
  },
} satisfies ChartConfig;

export const SiteVisitStatCard = () => {
  const [activeChart, setActiveChart] = useState<keyof typeof chartConfig>("desktop");

  const total = useMemo(
    () => ({
      desktop: chartData.reduce((acc, curr) => acc + curr.desktop, 0),
      mobile: chartData.reduce((acc, curr) => acc + curr.mobile, 0),
    }),
    [],
  );

  return (
    <>
      <Card className="py-0">
        <CardHeader className="flex flex-col items-stretch border-b p-0! sm:flex-row">
          <div className="flex flex-1 flex-col justify-center gap-1 px-6 pt-4 pb-3 sm:py-0!">
            <CardTitle>Site Visits</CardTitle>
            <CardDescription className="text-green-500">Total otal site visitors for the last 2 months</CardDescription>
          </div>
          <div className="flex">
            {["desktop", "mobile"].map((device) => {
              const chart = device as keyof typeof chartConfig;
              return (
                <button
                  key={chart}
                  data-active={activeChart === chart}
                  className="relative z-30 flex flex-1 flex-col justify-center gap-1 border-t px-6 py-4 text-left even:border-l data-[active=true]:bg-muted/50 sm:border-t-0 sm:border-l sm:px-8 sm:py-6"
                  onClick={() => setActiveChart(chart)}
                >
                  <span className="text-xs text-muted-foreground">{chartConfig[chart].label}</span>
                  <span className="text-sm leading-none font-bold tabular-nums md:text-2xl">
                    {total[device as keyof typeof total].toLocaleString()}
                  </span>
                </button>
              );
            })}
          </div>
        </CardHeader>

        <CardContent className="px-2 md:p-6">
          <ChartContainer config={chartConfig} className="aspect-auto h-45 w-full">
            <BarChart
              accessibilityLayer
              data={chartData}
              margin={{
                left: 4,
                right: 4,
              }}
            >
              <XAxis
                dataKey="date"
                tickLine={true}
                axisLine={true}
                tickMargin={8}
                minTickGap={20}
                tickFormatter={(value) => {
                  const date = new Date(value);
                  return date.toLocaleDateString("en-US", {
                    month: "short",
                    day: "numeric",
                  });
                }}
              />

              <ChartTooltip
                content={
                  <ChartTooltipContent
                    className="w-37.5"
                    nameKey="views"
                    labelFormatter={(value) => {
                      return new Date(value).toLocaleDateString("en-US", {
                        month: "short",
                        day: "numeric",
                        year: "numeric",
                      });
                    }}
                  />
                }
              />
              
              <Bar dataKey={activeChart} fill={`var(--color-${activeChart})`} />
            </BarChart>
          </ChartContainer>
        </CardContent>
      </Card>
    </>
  );
};
